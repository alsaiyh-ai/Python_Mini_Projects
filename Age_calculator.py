age=int(input("What’s Your Age ?"))
months=age*12
days=age*365
weeks=days//7
hours=days*24
minutes=hours*602
seconds=minutes*60

print("You lived for:- ")
print(f"{months} months")
print(f"{weeks} weeks")
print(f"{days} days")
print(f"{hours:,} hours")   
print(f"{minutes:,} minutes")
print(f"{seconds:,} seconds")










